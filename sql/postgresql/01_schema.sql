-- 공통 + 샘플 테이블 (PostgreSQL)
-- 컬럼명은 UPPER_SNAKE 로 쓰지만 PostgreSQL 은 소문자로 저장한다. 조회 결과의 code_nm 도 백엔드가 codeNm 으로 바꾼다.

-- 공통 컬럼 규칙: REG_ID, REG_DT, MOD_ID, MOD_DT

CREATE TABLE TB_COMM_CODE_GROUP (
    GROUP_CD    VARCHAR(30)   NOT NULL,
    GROUP_NM    VARCHAR(100)  NOT NULL,
    USE_YN      CHAR(1)       DEFAULT 'Y' NOT NULL,
    REG_ID      VARCHAR(20),
    REG_DT      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MOD_ID      VARCHAR(20),
    MOD_DT      TIMESTAMP,
    CONSTRAINT PK_COMM_CODE_GROUP PRIMARY KEY (GROUP_CD),
    CONSTRAINT CK_COMM_CODE_GROUP_USE_YN CHECK (USE_YN IN ('Y', 'N'))
);
COMMENT ON TABLE TB_COMM_CODE_GROUP IS '공통코드 그룹';

CREATE TABLE TB_COMM_CODE (
    GROUP_CD    VARCHAR(30)   NOT NULL,
    CODE        VARCHAR(30)   NOT NULL,
    CODE_NM     VARCHAR(100)  NOT NULL,
    SORT_ORD    INTEGER       DEFAULT 0 NOT NULL,
    USE_YN      CHAR(1)       DEFAULT 'Y' NOT NULL,
    REG_ID      VARCHAR(20),
    REG_DT      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MOD_ID      VARCHAR(20),
    MOD_DT      TIMESTAMP,
    CONSTRAINT PK_COMM_CODE PRIMARY KEY (GROUP_CD, CODE),
    CONSTRAINT FK_COMM_CODE_GROUP FOREIGN KEY (GROUP_CD) REFERENCES TB_COMM_CODE_GROUP (GROUP_CD),
    CONSTRAINT CK_COMM_CODE_USE_YN CHECK (USE_YN IN ('Y', 'N'))
);
COMMENT ON TABLE TB_COMM_CODE IS '공통코드';

-- 샘플 업무 테이블
CREATE TABLE TB_USER (
    USER_ID     VARCHAR(20)   NOT NULL,
    USER_NM     VARCHAR(50)   NOT NULL,
    DEPT_CD     VARCHAR(30)   NOT NULL,
    EMAIL       VARCHAR(100),
    JOIN_DT     DATE,
    SALARY      NUMERIC(15),
    USE_YN      CHAR(1)       DEFAULT 'Y' NOT NULL,
    REMARK      VARCHAR(500),
    REG_ID      VARCHAR(20),
    REG_DT      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MOD_ID      VARCHAR(20),
    MOD_DT      TIMESTAMP,
    CONSTRAINT PK_USER PRIMARY KEY (USER_ID),
    CONSTRAINT CK_USER_USE_YN CHECK (USE_YN IN ('Y', 'N'))
);
COMMENT ON TABLE TB_USER IS '사용자 (샘플)';
CREATE INDEX IX_USER_DEPT ON TB_USER (DEPT_CD);

-- 배치도 (좌석·설비·매장 진열 등). 도면 하나에 항목 여러 개, 좌표·크기는 도면 기준 단위
CREATE TABLE TB_LAYOUT_MAP (
    MAP_ID      VARCHAR(20)   NOT NULL,
    MAP_NM      VARCHAR(100)  NOT NULL,
    WIDTH       INTEGER       NOT NULL,
    HEIGHT      INTEGER       NOT NULL,
    BG_URL      VARCHAR(500),
    SORT_ORD    INTEGER       DEFAULT 0 NOT NULL,
    USE_YN      CHAR(1)       DEFAULT 'Y' NOT NULL,
    REG_ID      VARCHAR(20),
    REG_DT      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MOD_ID      VARCHAR(20),
    MOD_DT      TIMESTAMP,
    CONSTRAINT PK_LAYOUT_MAP PRIMARY KEY (MAP_ID),
    CONSTRAINT CK_LAYOUT_MAP_USE_YN CHECK (USE_YN IN ('Y', 'N'))
);
COMMENT ON TABLE TB_LAYOUT_MAP IS '배치도 도면';

CREATE TABLE TB_LAYOUT_ITEM (
    MAP_ID      VARCHAR(20)   NOT NULL,
    ITEM_ID     VARCHAR(30)   NOT NULL,
    ITEM_NM     VARCHAR(50),
    ITEM_TYPE   VARCHAR(30)   NOT NULL,
    POS_X       INTEGER       DEFAULT 0 NOT NULL,
    POS_Y       INTEGER       DEFAULT 0 NOT NULL,
    WIDTH       INTEGER       NOT NULL,
    HEIGHT      INTEGER       NOT NULL,
    ROTATE      INTEGER       DEFAULT 0 NOT NULL,
    SHAPE       VARCHAR(10)   DEFAULT 'rect' NOT NULL,
    USER_ID     VARCHAR(20),
    REG_ID      VARCHAR(20),
    REG_DT      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MOD_ID      VARCHAR(20),
    MOD_DT      TIMESTAMP,
    CONSTRAINT PK_LAYOUT_ITEM PRIMARY KEY (MAP_ID, ITEM_ID),
    CONSTRAINT FK_LAYOUT_ITEM_MAP FOREIGN KEY (MAP_ID) REFERENCES TB_LAYOUT_MAP (MAP_ID),
    CONSTRAINT CK_LAYOUT_ITEM_SHAPE CHECK (SHAPE IN ('rect', 'circle')),
    CONSTRAINT CK_LAYOUT_ITEM_ROTATE CHECK (ROTATE IN (0, 90, 180, 270))
);
COMMENT ON TABLE TB_LAYOUT_ITEM IS '배치도 항목 (좌석이면 USER_ID 로 사용자 배정)';
